// OPTIONAL maintenance tool. Derives the web project's data/code from the Snapchat Lens project (READ-ONLY).
// Needs the Lens project checked out as ../mr-puzzles-lens (it lives in the Claude-Code-Storage repo); NOT needed to run or deploy the site.
//   node tools/sync_from_lens.js
// so both versions share ONE source of truth for the model, the baked face-rig data and the expression mapping.
'use strict';
const fs = require('fs'), path = require('path');
const lens = path.join(__dirname, '..', '..', 'mr-puzzles-lens', 'Assets');
const web = path.join(__dirname, '..');
const rd = f => fs.readFileSync(path.join(lens, f), 'utf8');

// 1. rig data (bones rest positions + per-control bone offsets) -> JSON
const rig = require(path.join(lens, 'Scripts', 'RigData.js'));
fs.writeFileSync(path.join(web, 'data', 'rig.json'), JSON.stringify(rig));

// 2. ES-module copies of the pure logic (only the export line changes)
function toEsm(src, banner) {
  const m = src.match(/module\.exports\s*=\s*\{([^}]*)\};?\s*$/);
  if (!m) throw new Error('unexpected module.exports shape');
  const names = m[1].split(',').map(s => s.split(':')[0].trim()).filter(Boolean);
  return `// ${banner}\n` + src.replace(/'use strict';\n?/, '').replace(/module\.exports\s*=\s*\{[^}]*\};?\s*$/, `export { ${names.join(', ')} };\n`);
}
const GEN = 'GENERATED by tools/sync_from_lens.js from mr-puzzles-lens - edit the Lens version, then re-sync.';
fs.writeFileSync(path.join(web, 'js', 'mood.js'), toEsm(rd('Scripts/MoodLogic.js'), GEN));
fs.writeFileSync(path.join(web, 'js', 'demo_presets.js'), toEsm(rd('Scripts/DemoPresets.js'), GEN));

// 3. the model
fs.copyFileSync(path.join(lens, 'Models', 'MrPuzzles_Head.glb'), path.join(web, 'models', 'MrPuzzles_Head.glb'));
fs.copyFileSync(path.join(lens, 'Textures', 'MP_Label.png'), path.join(web, 'models', 'label.png'));
console.log('synced: data/rig.json, js/mood.js, js/demo_presets.js, models/MrPuzzles_Head.glb');
